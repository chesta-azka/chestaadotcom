export function getImageAsset(keyOrPath: string, locale: 'id' | 'en' = 'id'): SiteImageAsset {
  if (SITE_IMAGES[keyOrPath]) {
    const item = SITE_IMAGES[keyOrPath];
    return {
      ...item,
      alt: locale === 'en' && item.altEn ? item.altEn : item.alt,
    };
  }
  const found = Object.values(SITE_IMAGES).find((item) => item.src === keyOrPath);
  if (found) {
    return {
      ...found,
      alt: locale === 'en' && found.altEn ? found.altEn : found.alt,
    };
  }
  const isBlogCover =
    keyOrPath?.startsWith('/images/blog/covers/') || keyOrPath?.startsWith('cover-');
  return {
    key: 'custom',
    src: keyOrPath || SITE_IMAGES.ogDefault.src,
    alt:
      locale === 'en'
        ? 'Illustration of custom software and AI agent by CHESTAADOTCOM'
        : 'Ilustrasi software custom dan AI agent CHESTAADOTCOM',
    width: isBlogCover ? 1600 : 1200,
    height: isBlogCover ? 900 : 900,
    aspectRatio: isBlogCover ? '16:9' : '4:3',
    placeholderColor: '#F8F6FE',
    label: 'Ilustrasi',
    labelEn: 'Illustration',
  };
}

